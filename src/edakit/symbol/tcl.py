"""生成在 Capture 进程内运行的 TCL。

两条产物:
  * ``generate_capture_run_tcl`` —— 把 in.xml 转成 .olb 并回读校验 (XMATIC 往返);
  * ``generate_place_tcl``       —— 在原理图页放置符号并写属性 (PlacePart + Dbo*)。

后端降级: 无 XMATIC 时用 capCreatePartsFromData (仅方框)，见 generate_partsdata_tcl。
"""

from __future__ import annotations

import json
from pathlib import Path

from ..easyeda.model import Symbol


def _tcl_str(s: str) -> str:
    """TCL 双引号字符串转义。"""
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("[", "\\[")


def generate_capture_run_tcl(
    dll_path: str,
    xml_path: str,
    olb_path: str,
    roundtrip_path: str,
) -> str:
    """XML → OLB → 回读校验。核心就是这几行 (见技术方案 3.3)。"""
    d = _tcl_str(dll_path)
    xi = _tcl_str(xml_path)
    ol = _tcl_str(olb_path)
    rt = _tcl_str(roundtrip_path)
    return f"""# Auto-generated by edakit — Capture 库 XML -> OLB 往返
if {{[catch {{
    load "{d}" DboTclWriteBasic
    XMATIC_XML2OLB "{xi}" "{ol}"
    if {{![file exists "{ol}"]}} {{error "Capture 未生成 OLB"}}
    XMATIC_OLB2XML "{ol}" "{rt}"
    if {{![file exists "{rt}"]}} {{error "Capture 未生成回读 XML"}}
    # Capture must rewrite its own exported XML before placement. A direct
    # XML2OLB result can scatter pins even when the readback coordinates match.
    XMATIC_XML2OLB "{rt}" "{ol}"
    XMATIC_OLB2XML "{ol}" "{rt}"
    puts "EDAKIT_OLB_OK"
}} err]}} {{
    puts "EDAKIT_OLB_FAIL: $err"
}}
"""


def generate_place_tcl(
    olb_path: str,
    part_name: str,
    x_mm: float = 25.4,
    y_mm: float = 25.4,
    subpart: str = "",
    props: dict[str, str] | None = None,
) -> str:
    """在原理图上放一个元件并写属性。

    PlacePart 细节: 路径必须用正斜杠; 第 5 参是子部件字母 (无则 "")。
    属性走 Dbo* 接口 (文档 §3.5)。
    """
    olb = _tcl_str(olb_path.replace("\\", "/"))
    part = _tcl_str(part_name)
    sub = _tcl_str(subpart)
    lines: list[str] = []
    lines.append("# Auto-generated by edakit — 放置并写属性")
    lines.append("if {[catch {")
    lines.append(f'    set lStatus [DboState]')
    lines.append(f'    PlacePart {x_mm:.4f} {y_mm:.4f} "{olb}" "{part}" "{sub}" FALSE')
    lines.append('    puts "EDAKIT_PLACE_OK"')
    lines.append("} err] {")
    lines.append('    puts "EDAKIT_PLACE_FAIL: $err"')
    lines.append("}")
    if props:
        lines.append("")
        lines.append("# 实例属性 (需先拿到刚放置的 instance; 由上层指针传入或按需遍历)")
        lines.append("set lProps {")
        for k, v in props.items():
            lines.append(f'    {{{_tcl_str(k)}}} {{{_tcl_str(v)}}}')
        lines.append("}")
        lines.append("foreach {pname pval} $lProps {")
        lines.append('    catch {$lPlacedInst SetEffectivePropStringValue $pname $pval} __e')
        lines.append("}")
    return "\n".join(lines) + "\n"


def generate_partsdata_tcl(
    part_name: str,
    prefix: str,
    olb_path: str,
    pins: list[tuple[str, str]],
    split_max: str = "1",
) -> str:
    """降级后端: capCreatePartsFromData。

    脚本里没有矩形/线/弧的输入 —— 这是「给引脚、由 Capture 自动生成矩形本体」的路线。
    **符号外观会退化成方框**，仅在无 XMATIC 的老版本上用。

    每条引脚 8 字段: {引脚号 引脚名 类型 可见性 线型 分组 侧 页}
    """
    olb = _tcl_str(olb_path)
    lines = ["# Auto-generated (降级: 方框符号)"]
    lines.append(f'set outString "{olb}"')
    lines.append("set FinalList [list]")
    lines.append(
        f'lappend FinalList [list "{_tcl_str(part_name)}" "{split_max}" '
        f'"{_tcl_str(prefix)}" "1"]'
    )
    for number, name in pins:
        lines.append(
            f'lappend FinalList [list "{_tcl_str(number)}" "{_tcl_str(name)}" '
            f'"Passive" "1" "0" "0" "Left" "1"]'
        )
    lines.append('capCreatePartsFromData "false" $outString [list $FinalList]')
    return "\n".join(lines) + "\n"


def write_tcl(path: str | Path, content: str) -> None:
    Path(path).write_text(content, encoding="utf-8", newline="\n")


def dump_props(props: dict[str, str]) -> str:
    return json.dumps(props, ensure_ascii=False, indent=2)
