"""生成 Allegro SKILL 脚本 (.il) 来建封装。

.dra / .psm / .pad 都是二进制数据库，外部程序不能直接写，唯一可行架构是:
    外部程序准备数据 → 生成 SKILL → 在装了 Allegro 的机器上让 Allegro 自己执行 → 回读校验。

!! 函数签名 !!
SKILL 函数名与参数以 Cadence SKILL Reference 为准。几个常被 AI 记错的:
  * 建 padstack 是 ``axlDBCreatePadStack`` (大写 S)，**不是** ``axlPadstackCreate``;
  * 没有 ``axlDBSaveAs``，存盘是 ``axlSaveDesign`` + ``axlCompileSymbol``。
参数细节 (figureSize 的 'w:h' 写法等) 落地时在 17.2/17.4/22.1 上各跑一次校准。
"""

from __future__ import annotations

from ..easyeda.model import Footprint, Padstack

# 语义层名 → SKILL 层名
_SKILL_LAYERS = {
    "TOP": "TOP",
    "BOTTOM": "BOTTOM",
    "TOP_SOLDERMASK": "SOLDERMASK_TOP",
    "BOTTOM_SOLDERMASK": "SOLDERMASK_BOTTOM",
    "TOP_PASTE": "PASTEMASK_TOP",
    "BOTTOM_PASTE": "PASTEMASK_BOTTOM",
}
SILK_TOP = "PACKAGE GEOMETRY/SILKSCREEN_TOP"
SILK_BOTTOM = "PACKAGE GEOMETRY/SILKSCREEN_BOTTOM"
ASSY_TOP = "PACKAGE GEOMETRY/ASSEMBLY_TOP"
PLACE_BOUND_TOP = "PACKAGE GEOMETRY/PLACE_BOUND_TOP"

LINE_WIDTH_MM = 0.12  # 丝印线宽默认值


def _s(name: str) -> str:
    return name.replace("\\", "\\\\").replace('"', '\\"')


def generate_skill(fp: Footprint, *, drill_plated: bool = True) -> str:
    """把 Footprint 翻成一段可 load 的 SKILL。"""
    dra = f"{_s(fp.name)}.dra"
    out: list[str] = []
    add = out.append

    add("/* Auto-generated by lcsc2cadence. 不要手改，重新生成即可。 */")
    add('(defun lcsc_build_footprint ()')
    add("  (let (dr padFigure)")
    add(f'    (axlOpenDesign ?design "{dra}" ?mode "wf" ?noMru t)')
    add('    (axlSetSymbolType "package")')

    add("    /* ---- padstacks ---- */")
    for ps in fp.padstacks:
        add(_skill_padstack(ps))

    add("    /* ---- pins ---- */")
    for ps in fp.padstacks:
        add(_skill_pin(ps))

    add("    /* ---- silkscreen ---- */")
    for layer, pts in fp.lines:
        target = _silk_layer(layer)
        if target is None or len(pts) < 2:
            continue
        coords = " ".join(f"{x:.4f} {y:.4f}" for x, y in pts)
        add(f'    (axlDBCreateLine (list {coords}) "{target}" {LINE_WIDTH_MM})')
    for layer, cx, cy, r in fp.circles:
        target = _silk_layer(layer)
        if target is None:
            continue
        add(f'    (axlDBCreateCircle (list {cx:.4f} {cy:.4f}) {r:.4f} "{target}")')

    add("    /* ---- place bound ---- */")
    add(_skill_place_bound(fp))

    add("    /* ---- save & compile ---- */")
    add('    (axlSaveDesign ?design ?mode "nocheck" ?noMru t)')
    add('    (axlCompileSymbol ?symbol "package")')
    add("  )")
    add(")")
    add("")
    add("(lcsc_build_footprint)")
    add("")
    return "\n".join(out)


def _skill_padstack(ps: Padstack) -> str:
    out: list[str] = []
    name = _s(ps.name)
    # SMD (无钻孔) 用 nil, 不要 (list ) —— 部分 SKILL 版本对空 list 报错
    drill = f"(make_axlPadStackDrill ?diameter {ps.drill_mm:.4f})" if ps.drill_mm > 0 else "nil"
    pads: list[str] = []
    for lay in ps.layers:
        skill_layer = _SKILL_LAYERS.get(lay.layer, lay.layer)
        size = f"{lay.w_mm:.4f}:{lay.h_mm:.4f}"
        pads.append(f'      (make_axlPadStackPad ?layer "{skill_layer}" ?figureSize "{size}")')
    out.append(f'    (axlDBCreatePadStack "{name}"')
    out.append(f"      (list {drill})")
    out.append("      (list")
    out.extend(pads)
    out.append("      )")
    out.append("    )")
    return "\n".join(out)


def _skill_pin(ps: Padstack) -> str:
    return (
        f'    (axlDBCreatePin (list "{_s(ps.name)}") '
        f"(list {ps.x_mm:.4f} {ps.y_mm:.4f}) "
        f'(make_axlPinText ?text "{_s(ps.name)}" '
        f"?orientation (make_axlTextOrientation ?textAngle 0.0)) "
        f"{ps.rotation_deg:.2f})"
    )


def _silk_layer(layer: str) -> str | None:
    return {
        "TOP_SILK": SILK_TOP,
        "BOTTOM_SILK": SILK_BOTTOM,
        "TOP_ASSEMBLY": ASSY_TOP,
        "BOARD_OUTLINE": SILK_TOP,
    }.get(layer)


def _skill_place_bound(fp: Footprint) -> str:
    """由焊盘外扩出 place_bound 矩形。"""
    xs, ys = [], []
    for pad in fp.pads:
        xs += [pad.x_mm - pad.w_mm / 2, pad.x_mm + pad.w_mm / 2]
        ys += [pad.y_mm - pad.h_mm / 2, pad.y_mm + pad.h_mm / 2]
    if not xs:
        return "    /* 无焊盘，跳过 place bound */"
    margin = 0.2
    x1, x2 = min(xs) - margin, max(xs) + margin
    y1, y2 = min(ys) - margin, max(ys) + margin
    coords = (
        f"{x1:.4f} {y1:.4f} {x2:.4f} {y1:.4f} {x2:.4f} {y2:.4f} "
        f"{x1:.4f} {y2:.4f} {x1:.4f} {y1:.4f}"
    )
    return f'    (axlDBCreateShape (list {coords}) "{PLACE_BOUND_TOP}")'
