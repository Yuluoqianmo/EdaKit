"""Structural contracts; adapters remain ordinary Python classes."""
from typing import Any, Protocol
from ..catalog.models import Part, SearchResult, CategoryNode


class CatalogProvider(Protocol):
    def search_keyword(self, keyword: str, *, page: int, page_size: int, **options) -> SearchResult: ...
    def browse_category(self, cat: int, *, page: int, page_size: int, **options) -> SearchResult: ...
    def category_tree(self) -> list[CategoryNode]: ...
    def product_detail(self, cid: str) -> Part: ...
    def package_options(self, catalog_ids: list[int], keyword: str = "") -> dict: ...
    def facet_options(self, catalog_ids: list[int], keyword: str = "") -> dict: ...


class ComponentProvider(Protocol):
    def get_component(self, cid: str) -> dict[str, Any]: ...


class ModelProvider(Protocol):
    def download_obj_bytes(self, uuid: str) -> bytes: ...
