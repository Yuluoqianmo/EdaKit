def value_label(key: str, value: str) -> str:
    """Display a known whole value; unknown technical values stay intact."""
    return _VALUES.get(_alias(key), {}).get(_alias(value), value)


def parameter_display(key: str, values: Iterable[str] = (),
                      catalog_ids: Iterable[int] = ()) -> dict[str, Any]:
    """Resolve a display name using observed values and a known category scope."""
    canonical = key if key in LABELS else _KEYS.get(_alias(key), key)
    label = LABELS.get(canonical, key)
    samples = list(values)
    normalized = {_alias(v) for v in samples}
    ids = set(catalog_ids)
    note = NOTES.get(canonical, '')
    review = REVIEW_NOTES.get(canonical, '')
    if _alias(canonical) == 'output type' and normalized:
        if normalized <= {'adjustable', 'fixed', 'adjustable and fixed'}:
            label = '输出电压类型'
        elif normalized <= {'open-drain', 'open drain', 'open collector', 'open-collector',
                            'push-pull', 'complementary', 'cmos', 'ttl', 'tri-state'}:
            label = '输出形式'
    if canonical == 'Function' and normalized and normalized <= set(_TOPOLOGIES):
        label = '转换功能'
    if canonical == 'Tolerance':
        if ids and ids <= set(RESISTOR_IDS):
            label = '阻值精度'
        elif ids and ids <= set(CAPACITOR_IDS):
            label = '容量偏差'
        elif ids and ids <= set(INDUCTOR_IDS):
            label = '感量偏差'
    if canonical == 'Temperature Coefficient' and normalized:
        if all(re.fullmatch(r'(?:[cuxyz]\d[a-z0-9]|np0|c0g)', v) for v in normalized):
            label = '介质/温度特性'
        elif ids and ids <= set(RESISTOR_IDS):
            label = '温度系数（TCR）'
    if canonical == 'Channel Type':
        # This field is direction in logic translators; not MOSFET polarity.
        if normalized and not normalized <= {'bidirectional', 'unidirectional'}:
            label = '通道类型'
    if canonical == 'Resolution (Bits)':
        if any(re.search(r'(?:hz|sps)', v, re.I) for v in samples):
            review = '上游将频率/采样速率放在分辨率字段中，单位与字段不符；请查具体器件手册。'
        elif normalized and all(re.fullmatch(r'\d+(?:\s*bits?)?', v) for v in normalized):
            review = ''
    return {'label': label, 'note': review or note, 'needsReview': bool(review),
            'translated': canonical in LABELS}


def display_params(params: dict[str, str], catalog_id: int | None = None) -> list[dict[str, Any]]:
    """Keep raw params alongside display rows rather than replacing their identity."""
    return [dict(key=key, value=value, displayValue=value_label(key, value),
                 **parameter_display(key, [value], [catalog_id] if catalog_id else []))
            for key, value in params.items()]

