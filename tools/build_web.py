"""Deterministic ES3 bundle; no runtime module loader or dependencies."""
from pathlib import Path
import sys
ROOT = Path(__file__).resolve().parents[1]

def build(check=False):
    source = ROOT / "frontend"
    target = ROOT / "src/edakit/server/web"
    for extension in ("js", "css"):
        files = sorted(source.glob("*." + extension))
        body = "\n".join("/* source: " + path.name + " */\n" + path.read_text(encoding="utf-8") for path in files)
        if extension == "js":
            body = "/* Generated by tools/build_web.py; edit frontend sources. */\n(function () {\n" + body + "\n})();\n"
        output = target / ("embed." + extension)
        if check:
            if output.read_text(encoding="utf-8") != body:
                raise SystemExit(str(output) + " is stale; run python tools/build_web.py")
        else:
            output.write_text(body, encoding="utf-8", newline="\n")

if __name__ == "__main__":
    build("--check" in sys.argv)
